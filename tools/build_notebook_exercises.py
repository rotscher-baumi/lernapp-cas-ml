"""Generate ``assets/notebook-data.js`` from the exercise notebooks.

The notebooks are the source of truth; the web app renders the very same tasks, start code,
checks and solutions from the generated file.

Usage::

    python lernapp/tools/build_notebook_exercises.py            # write the file
    python lernapp/tools/build_notebook_exercises.py --check    # fail if the file is stale
    python lernapp/tools/build_notebook_exercises.py --verify   # run every solution against its check
"""

import argparse
import html
import json
import logging
import os
import re
import sys
from pathlib import Path

logger = logging.getLogger("build_notebook_exercises")

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOKS = ["Python_Pandas_Uebungen_own.ipynb", "Supervised_Learning_1_Uebungen_own.ipynb"]
OUTPUT = ROOT / "assets" / "notebook-data.js"

TITLE_RE = re.compile(r"^### Aufgabe (\d+): (.+)$", re.MULTILINE)
SOLUTION_RE = re.compile(r"```python\n(.*?)\n```", re.DOTALL)


def _source(cell: dict) -> str:
    return "".join(cell["source"])


def _inline(text: str) -> str:
    """Convert inline markdown (code, bold) to HTML."""
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    return re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)


def markdown_to_html(text: str) -> str:
    """Convert the small markdown subset used in the task cells to HTML.

    :param text: markdown source of a task cell without its heading
    :type text: str
    :return: HTML fragment
    :rtype: str
    """
    out: list[str] = []
    para: list[str] = []
    items: list[str] = []
    list_tag = ""

    def flush_para() -> None:
        if para:
            out.append("<p>" + _inline(" ".join(para)) + "</p>")
            para.clear()

    def flush_list() -> None:
        nonlocal list_tag
        if items:
            out.append(f"<{list_tag}>" + "".join(f"<li>{_inline(i)}</li>" for i in items) + f"</{list_tag}>")
            items.clear()
            list_tag = ""

    for line in text.split("\n"):
        ordered = re.match(r"^\d+\.\s+(.*)$", line)
        bullet = re.match(r"^-\s+(.*)$", line)
        if ordered or bullet:
            flush_para()
            tag = "ol" if ordered else "ul"
            if list_tag and list_tag != tag:
                flush_list()
            list_tag = tag
            items.append((ordered or bullet).group(1))
        elif line.strip():
            flush_list()
            para.append(line.strip())
        else:
            flush_para()
            flush_list()
    flush_para()
    flush_list()
    return "".join(out)


def parse_notebook(path: Path) -> dict:
    """Extract setup code and exercises from one exercise notebook.

    :param path: notebook file
    :type path: Path
    :return: dict with ``setup`` and ``exercises``
    :rtype: dict
    """
    cells = json.loads(path.read_text(encoding="utf-8"))["cells"]
    setup = _source(cells[1])
    exercises = []
    i = 2
    while i < len(cells):
        match = TITLE_RE.match(_source(cells[i]))
        if cells[i]["cell_type"] != "markdown" or not match:
            raise ValueError(f"{path.name}: cell {i} is not an exercise heading")
        task_md = _source(cells[i])
        task_md = task_md[match.end() :].strip()
        solution = SOLUTION_RE.search(_source(cells[i + 3]))
        if cells[i + 1]["cell_type"] != "code" or cells[i + 2]["cell_type"] != "code" or not solution:
            raise ValueError(f"{path.name}: exercise {match.group(1)} is not task/start/check/solution")
        exercises.append(
            {
                "t": match.group(2),
                "task": markdown_to_html(task_md),
                "start": _source(cells[i + 1]),
                "check": _source(cells[i + 2]),
                "sol": solution.group(1),
            }
        )
        i += 4
    return {"setup": setup, "exercises": exercises}


def build() -> str:
    """Build the content of the generated JavaScript file.

    :return: JavaScript source
    :rtype: str
    """
    data = {name: parse_notebook(ROOT / "notebooks" / name) for name in NOTEBOOKS}
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return (
        "/* Generated by tools/build_notebook_exercises.py from notebooks/*.ipynb. Do not edit by hand. */\n"
        f"window.NbData = {body};\n"
    )


def verify() -> bool:
    """Run every solution followed by its check, as a user who solves all exercises in order.

    :return: True if all checks pass
    :rtype: bool
    """
    os.environ["MPLBACKEND"] = "Agg"
    all_ok = True
    for name in NOTEBOOKS:
        nb = parse_notebook(ROOT / "notebooks" / name)
        ns: dict = {"__name__": "__main__"}
        exec(nb["setup"], ns)  # noqa: S102 - trusted repo code
        for n, ex in enumerate(nb["exercises"], start=1):
            try:
                exec(ex["sol"], ns)  # noqa: S102
                exec(ex["check"], ns)  # noqa: S102
            except Exception:
                logger.exception("%s exercise %d failed", name, n)
                all_ok = False
    return all_ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    parser.add_argument("--verify", action="store_true", help="run all solutions against their checks")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    content = build()
    if args.verify:
        ok = verify()
        logger.info("verify: %s", "all exercises pass" if ok else "FAILED")
        return 0 if ok else 1
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            logger.error("%s is stale; run build_notebook_exercises.py", OUTPUT.name)
            return 1
        logger.info("up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    logger.info("wrote %s", OUTPUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
